#!/usr/bin/env python3
"""Build ``app/kria/copy/tr.json`` from the code's own ``say(en=..., tr=...)`` texts (KRI-1362).

Kria's chat sentences are looked up per language by their English text
(``app/kria/copy_catalog.py``). Turkish stays inline in the code (``tr=``) so open PRs keep
working; ``tr.json`` is a generated mirror of it, the reference a translator (German first)
works from, and the source of the ``qps`` pseudo language that shows which sentences the
catalog does not reach yet.

What is harvested (``ast`` only, from ``src/apps/api/app``), by kind:

* ``literal``         ``say(en="...", tr="...")``, templates included
                      (``"No pop-in for {names}"``).
* ``constant_name``   ``say(en=NAME, tr=NAME_TR)`` with module-level string constants (also
                      imported from another ``app`` module, or a function-local name assigned
                      once).
* ``conditional``     ``say(en=A if c else B, tr=C if c else D)`` with the same condition, every
                      branch a literal or constant name; a constant ``tr`` pairs with each branch.
* ``table_english_keyed``  ``say(en=reason, tr=_REASON_TR.get(reason, reason))``: a module
                      dict keyed by the English sentences (literals or names bound to literals),
                      entries added later by ``T[K] = V`` / ``T.update({...})`` included.
* ``table_parallel``  ``say(en=_X[code], tr=_X_TR[code])`` (or ``.get``): two dicts with shared
                      keys (the English side may be ``A.get(k) or B.get(k)``).
* ``table_pairs``     ``say(en=_X[code][0], tr=_X[code][1])``: a dict of ``(english, turkish)``
                      tuples (also a dict literal at the call site, or a local unpacked from one).
* ``wrapper``         a call to a module-level function that forwards its parameters (or the
                      halves of an ``(en, tr)`` tuple parameter) to ``say(en=..., tr=...)``.

Anything else (a concatenation, a call, an f-string, a name that does not resolve) is listed in
``skipped`` with file:line and the reason; nothing is dropped silently. The same English key with
different Turkish texts in different places is a conflict: the first in sorted file:line order
wins in ``tr.json``, and every place is written to ``conflicts.json`` for the reviewer (German
needs one translation per key).

    python3 scripts/kria/build_copy_catalog.py            # write tr.json + conflicts.json
    python3 scripts/kria/build_copy_catalog.py --check    # exit 1 when either file is stale
    python3 scripts/kria/build_copy_catalog.py --report out.json

Stdlib only.
"""

