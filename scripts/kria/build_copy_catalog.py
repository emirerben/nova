# ---------------------------------------------------------------- results


@dataclass(frozen=True)
class Pair:
    en: str
    tr: str
    kind: str
    file: str  # relative to src/apps/api, e.g. "app/kria/brief_checks.py"
    line: int
    # How to re-check this pair against the imported code (tests): ("say",) for a call site,
    # ("table", module, table, key) / ("parallel", module, en_table, tr_table, key) /
    # ("pairs", module, table, key), ("names", (module, name) | None, (module, name) | None).
    origin: tuple = ()


@dataclass(frozen=True)
class Skip:
    file: str
    line: int
    reason: str
    detail: str = ""


@dataclass
class Harvest:
    pairs: list[Pair] = field(default_factory=list)
    skipped: list[Skip] = field(default_factory=list)
    tables: dict[str, dict] = field(default_factory=dict)
    wrappers: dict[str, dict] = field(default_factory=dict)
    excluded_tables: list[dict] = field(default_factory=list)
    unpaired_tables: list[dict] = field(default_factory=list)

    def messages(self) -> tuple[dict[str, str], dict[str, list[dict]]]:
        """``english -> turkish`` (first place in file:line order wins) and the conflicts."""
        places: dict[str, list[Pair]] = defaultdict(list)
        # stable: places on one line keep harvest (source) order
        for pair in sorted(self.pairs, key=lambda p: (p.file, p.line)):
            places[pair.en].append(pair)
        messages: dict[str, str] = {}
        conflicts: dict[str, list[dict]] = {}
        for en in sorted(places):
            found = places[en]
            messages[en] = found[0].tr
            if len({p.tr for p in found}) > 1:
                seen: set[tuple] = set()
                rows = []
                for p in found:
                    row = (p.file, p.line, p.tr)
                    if row not in seen:
                        seen.add(row)
                        rows.append({"file": p.file, "line": p.line, "tr": p.tr})
                conflicts[en] = rows
        return messages, conflicts


class Unresolved(Exception):
    pass


# ---------------------------------------------------------------- modules


def module_name(rel: str) -> str:
    parts = Path(rel).with_suffix("").parts
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _dump(node: ast.AST) -> str:
    return ast.dump(node, annotate_fields=False, include_attributes=False)


def _is_say(node: ast.AST) -> bool:
    return isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "say"


def _kw(call: ast.Call, name: str) -> ast.AST | None:
    return next((k.value for k in call.keywords if k.arg == name), None)


@dataclass
class Module:
    rel: str
    name: str
    tree: ast.Module
    assigns: dict[str, list[ast.AST]] = field(default_factory=dict)
    imports: dict[str, tuple[str, str]] = field(default_factory=dict)
    defs: dict[str, ast.FunctionDef | ast.AsyncFunctionDef] = field(default_factory=dict)
    # entries added after a dict is built: ``T[K] = V`` / ``T.update({...})`` at module level;
    # (key node, value node, line), key None when the entry cannot be read
    added: dict[str, list[tuple[ast.AST | None, ast.AST | None, int]]] = field(default_factory=dict)

    @classmethod
    def parse(cls, rel: str, text: str) -> Module:
        mod = cls(rel=rel, name=module_name(rel), tree=ast.parse(text))
        package = mod.name if rel.endswith("__init__.py") else mod.name.rpartition(".")[0]
        for node in mod.tree.body:
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        mod.assigns.setdefault(target.id, []).append(node.value)
            elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
                if node.value is not None:
                    mod.assigns.setdefault(node.target.id, []).append(node.value)
            elif isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
                mod.defs[node.name] = node
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Subscript) and isinstance(target.value, ast.Name):
                        rows = mod.added.setdefault(target.value.id, [])
                        rows.append((target.slice, node.value, node.lineno))
            elif (
                isinstance(node, ast.Expr)
                and isinstance(node.value, ast.Call)
                and isinstance(node.value.func, ast.Attribute)
                and node.value.func.attr == "update"
                and isinstance(node.value.func.value, ast.Name)
            ):
                rows = mod.added.setdefault(node.value.func.value.id, [])
                args = node.value.args
                if len(args) == 1 and isinstance(args[0], ast.Dict) and not node.value.keywords:
                    for key, value in zip(args[0].keys, args[0].values, strict=True):
                        rows.append((key, value, (key or value).lineno))
                else:
                    rows.append((None, None, node.lineno))
        for node in ast.walk(mod.tree):
            if isinstance(node, ast.ImportFrom):
                source = node.module or ""
                if node.level:
                    base = package.split(".")
                    base = base[: len(base) - (node.level - 1)] if node.level > 1 else base
                    source = ".".join([*base, source] if source else base)
                if not source.startswith("app"):
                    continue
                for alias in node.names:
                    mod.imports.setdefault(alias.asname or alias.name, (source, alias.name))
        return mod


class _LazyModules(Mapping):
    """``module name -> Module``, parsed on first use (most modules are never needed)."""

    def __init__(self, texts: Mapping[str, tuple[str, str]]) -> None:
        self._texts = texts
        self._parsed: dict[str, Module] = {}

    def __getitem__(self, name: str) -> Module:
        if name not in self._parsed:
            rel, text = self._texts[name]
            self._parsed[name] = Module.parse(rel, text)
        return self._parsed[name]

    def __iter__(self):
        return iter(self._texts)

    def __len__(self) -> int:
        return len(self._texts)


@dataclass(frozen=True)
class TableRef:
    module: str
    name: str


class Index:
    """Every ``app`` module, for resolving names across files."""

    def __init__(self, sources: Mapping[str, str]) -> None:
        self.texts: dict[str, tuple[str, str]] = {
            module_name(rel): (rel, sources[rel]) for rel in sorted(sources)
        }
        self.modules = _LazyModules(self.texts)
        self.inline: dict[TableRef, ast.Dict] = {}

    def inline_table(self, mod: Module, node: ast.Dict) -> TableRef:
        """A dict literal written at the call site (``{"met": ("Done", "Yapıldı")}[status]``)."""
        ref = TableRef(mod.name, f"<dict at line {node.lineno}>")
        self.inline[ref] = node
        return ref

    def having(self, *needles: str) -> list[Module]:
        """Modules whose source contains any of ``needles`` (parsing only those)."""
        return [
            self.modules[name]
            for name, (_rel, text) in self.texts.items()
            if any(n in text for n in needles)
        ]

    # constants -----------------------------------------------------

    def resolve_name(self, mod: Module, name: str, depth: int = 0) -> object:
        """A module-level constant's value (str, tuple, number) or a ``TableRef`` for a dict."""
        if depth > MAX_DEPTH:
            raise Unresolved("name chain too deep")
        values = mod.assigns.get(name)
        if values:
            if len(values) > 1:
                raise Unresolved(f"module name {name} assigned more than once")
            value = values[0]
            if _dict_node(value) is not None:
                return TableRef(mod.name, name)
            return self.const(value, mod, depth + 1)
        if name in mod.imports:
            source, original = mod.imports[name]
            target = self.modules.get(source)
            if target is None:
                raise Unresolved(f"{name} imported from {source}, not an app module")
            return self.resolve_name(target, original, depth + 1)
        raise Unresolved(f"name {name} not a module constant")

    def const(self, node: ast.AST, mod: Module, depth: int = 0) -> object:
        if depth > MAX_DEPTH:
            raise Unresolved("constant chain too deep")
        if isinstance(node, ast.Constant):
            return node.value
        if isinstance(node, ast.JoinedStr):
            if all(isinstance(v, ast.Constant) for v in node.values):
                return "".join(v.value for v in node.values)
            raise Unresolved("f-string")
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            left = self.const(node.left, mod, depth + 1)
            right = self.const(node.right, mod, depth + 1)
            if isinstance(left, str) and isinstance(right, str):
                return left + right
            raise Unresolved("non-string concatenation")
        if isinstance(node, ast.Tuple | ast.List):
            return tuple(self.const(e, mod, depth + 1) for e in node.elts)
        if isinstance(node, ast.Name):
            value = self.resolve_name(mod, node.id, depth + 1)
            if isinstance(value, TableRef):
                raise Unresolved(f"{node.id} is a table")
            return value
        raise Unresolved(f"{type(node).__name__} is not a constant")

    def table_entries(self, ref: TableRef) -> list[tuple[object, object, int, str | None]]:
        """(key, value, line, problem) for each entry; problem is None when both resolved."""
        mod = self.modules[ref.module]
        node = self.inline.get(ref) or _dict_node(mod.assigns[ref.name][0])
        assert node is not None
        rows = [((k or v).lineno, k, v) for k, v in zip(node.keys, node.values, strict=True)]
        if ref not in self.inline:
            rows += [(line, k, v) for k, v, line in mod.added.get(ref.name, [])]
        out = []
        for line, key, value in rows:
            if key is None and value is None:
                out.append((None, None, line, "entries added by a computed update()"))
                continue
            if key is None:
                out.append((None, None, line, "dict unpacking (**) entry"))
                continue
            try:
                k = self.const(key, mod)
            except Unresolved as exc:
                out.append((None, None, line, f"key not resolved: {exc}"))
                continue
            try:
                v = self.const(value, mod)
            except Unresolved as exc:
                out.append((k, None, line, f"value not resolved: {exc}"))
                continue
            out.append((k, v, line, None))
        return out


def _dict_node(node: ast.AST) -> ast.Dict | None:
    if isinstance(node, ast.Dict):
        return node
    if (
        isinstance(node, ast.Call)
        and len(node.args) == 1
        and not node.keywords
        and isinstance(node.args[0], ast.Dict)
    ):
        func = node.func
        fname = func.id if isinstance(func, ast.Name) else getattr(func, "attr", "")
        if fname in {"MappingProxyType", "dict"}:
            return node.args[0]
    return None


# ---------------------------------------------------------------- function scopes


class Scope:
    """One function's parameters and local bindings, worked out on first use."""

    def __init__(self, func: ast.FunctionDef | ast.AsyncFunctionDef | ast.Lambda) -> None:
        self.func = func
        self._data: tuple | None = None

    def _load(self) -> tuple:
        if self._data is None:
            self._data = _bindings(self.func)
        return self._data

    @property
    def params(self) -> set[str]:
        return self._load()[0]

    @property
    def assigns(self) -> dict[str, list[tuple[ast.AST, int | None]]]:
        """name -> [(value, unpack index)]"""
        return self._load()[1]

    @property
    def other_binds(self) -> Counter:
        """for/with/augassign/walrus/except/comprehension/def targets"""
        return self._load()[2]


def _own_nodes(func: ast.AST) -> Iterable[ast.AST]:
    """Nodes of ``func``'s body, not descending into nested functions or classes."""
    stack = list(ast.iter_child_nodes(func))
    while stack:
        node = stack.pop()
        yield node
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.Lambda | ast.ClassDef):
            continue
        stack.extend(ast.iter_child_nodes(node))


def _bindings(func: ast.FunctionDef | ast.AsyncFunctionDef | ast.Lambda) -> tuple:
    args = func.args
    params = {
        a.arg
        for a in (*args.posonlyargs, *args.args, *args.kwonlyargs, args.vararg, args.kwarg)
        if a is not None
    }
    assigns: dict[str, list[tuple[ast.AST, int | None]]] = defaultdict(list)
    other: Counter = Counter()

    def bind_target(target: ast.AST) -> None:
        for sub in ast.walk(target):
            if isinstance(sub, ast.Name):
                other[sub.id] += 1

    for node in _own_nodes(func):
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
            other[node.name] += 1
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    assigns[target.id].append((node.value, None))
                elif isinstance(target, ast.Tuple) and all(
                    isinstance(e, ast.Name) for e in target.elts
                ):
                    for i, e in enumerate(target.elts):
                        assigns[e.id].append((node.value, i))
                else:
                    bind_target(target)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            if node.value is not None:
                assigns[node.target.id].append((node.value, None))
        elif isinstance(node, ast.AugAssign):
            bind_target(node.target)
        elif isinstance(node, ast.For | ast.AsyncFor):
            bind_target(node.target)
        elif isinstance(node, ast.withitem) and node.optional_vars is not None:
            bind_target(node.optional_vars)
        elif isinstance(node, ast.NamedExpr):
            bind_target(node.target)
        elif isinstance(node, ast.ExceptHandler) and node.name:
            other[node.name] += 1
        elif isinstance(node, ast.comprehension):
            bind_target(node.target)
        elif isinstance(node, ast.Import | ast.ImportFrom):
            for alias in node.names:
                if isinstance(node, ast.Import):
                    other[(alias.asname or alias.name).split(".")[0]] += 1
    return params, dict(assigns), other


# ---------------------------------------------------------------- shapes

# A "shape" is what an en/tr expression amounts to, as a tuple:
#   ("lit", value, origin)        origin: None for a literal, (module, name, index) for a constant
#   ("cond", test_dump, a, b)
#   ("alts", [shapes])            ``a or b``
#   ("table", TableRef)
#   ("lookup", TableRef, key_dump, default_shape | None, index | None)
#   ("param", scope, name, index | None)
#   ("unknown", reason)
#   ("multi", name, [shapes])     a local bound more than once (only searched for tables)


@dataclass
class Ctx:
    index: Index
    mod: Module
    scopes: list[Scope]  # innermost last
    depth: int = 0

    def deeper(self) -> Ctx:
        return Ctx(self.index, self.mod, self.scopes, self.depth + 1)


def shape(node: ast.AST, ctx: Ctx) -> tuple:
    if ctx.depth > MAX_DEPTH:
        return ("unknown", "expression chain too deep")
    if isinstance(node, ast.Constant):
        if isinstance(node.value, str):
            return ("lit", node.value, None)
        return ("unknown", f"constant {type(node.value).__name__}")
    if isinstance(node, ast.JoinedStr):
        if all(isinstance(v, ast.Constant) for v in node.values):
            return ("lit", "".join(v.value for v in node.values), None)
        return ("unknown", "f-string")
    if isinstance(node, ast.Tuple):
        parts = [shape(e, ctx.deeper()) for e in node.elts]
        if all(p[0] == "lit" for p in parts):
            return ("lit", tuple(p[1] for p in parts), None)
        bad = next(p for p in parts if p[0] != "lit")
        return ("unknown", f"tuple part: {bad[1] if bad[0] == 'unknown' else bad[0]}")
    if isinstance(node, ast.Name):
        return _shape_name(node.id, ctx)
    if isinstance(node, ast.IfExp):
        return (
            "cond",
            _dump(node.test),
            shape(node.body, ctx.deeper()),
            shape(node.orelse, ctx.deeper()),
        )
    if isinstance(node, ast.BoolOp) and isinstance(node.op, ast.Or):
        return ("alts", [shape(v, ctx.deeper()) for v in node.values])
    if isinstance(node, ast.Dict):
        return ("table", ctx.index.inline_table(ctx.mod, node))
    if isinstance(node, ast.Subscript):
        base = shape(node.value, ctx.deeper())
        key = node.slice
        if isinstance(key, ast.Constant) and isinstance(key.value, int):
            return _index(base, key.value)
        if base[0] == "table":
            return ("lookup", base[1], _dump(key), None, None)
        if base[0] == "unknown":
            return base
        return ("unknown", "subscript of a non-table")
    if (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == "get"
        and 1 <= len(node.args) <= 2
        and not node.keywords
    ):
        base = shape(node.func.value, ctx.deeper())
        if base[0] == "table":
            default = shape(node.args[1], ctx.deeper()) if len(node.args) == 2 else None
            return ("lookup", base[1], _dump(node.args[0]), default, None)
        return ("unknown", "call .get on a non-table")
    if isinstance(node, ast.BinOp):
        return ("unknown", "concatenation (BinOp)")
    if isinstance(node, ast.Call):
        func = node.func
        fname = func.id if isinstance(func, ast.Name) else getattr(func, "attr", "?")
        return ("unknown", f"call {fname}()")
    return ("unknown", f"{type(node).__name__} expression")


def _index(base: tuple, i: int) -> tuple:
    kind = base[0]
    if kind == "lit" and isinstance(base[1], tuple):
        if not -len(base[1]) <= i < len(base[1]):
            return ("unknown", "tuple index out of range")
        origin = (*base[2][:2], i) if base[2] else None
        return ("lit", base[1][i], origin)
    if kind == "lookup" and base[4] is None:
        default = _index(base[3], i) if base[3] is not None else None
        return ("lookup", base[1], base[2], default, i)
    if kind == "param" and base[3] is None:
        return ("param", base[1], base[2], i)
    if kind == "cond":
        return ("cond", base[1], _index(base[2], i), _index(base[3], i))
    if kind == "alts":
        return ("alts", [_index(a, i) for a in base[1]])
    if kind == "multi":
        return ("multi", base[1], [_index(a, i) for a in base[2]])
    if kind == "unknown":
        return base
    return ("unknown", f"index [{i}] into {kind}")


def _shape_name(name: str, ctx: Ctx) -> tuple:
    for pos in range(len(ctx.scopes) - 1, -1, -1):
        scope = ctx.scopes[pos]
        assigned = scope.assigns.get(name, [])
        other = scope.other_binds.get(name, 0)
        is_param = name in scope.params
        if not (assigned or other or is_param):
            continue
        if is_param and not assigned and not other:
            return ("param", scope, name, None)
        inner = Ctx(ctx.index, ctx.mod, ctx.scopes[: pos + 1], ctx.depth + 1)
        found = [
            shape(value, inner) if unpack is None else _index(shape(value, inner), unpack)
            for value, unpack in assigned
        ]
        if is_param:
            return ("multi", f"parameter {name} reassigned", found)
        if other or len(assigned) != 1:
            return ("multi", f"local name {name} bound more than once", found)
        return found[0]
    try:
        value = ctx.index.resolve_name(ctx.mod, name)
    except Unresolved as exc:
        return ("unknown", f"name not resolved: {exc}")
    if isinstance(value, TableRef):
        return ("table", value)
    if isinstance(value, str | tuple):
        origin = (*_name_origin(ctx.index, ctx.mod, name), None)
        return ("lit", value, origin)
    return ("unknown", f"name {name} is not text")


def _name_origin(index: Index, mod: Module, name: str) -> tuple[str, str]:
    """(module, name) where a module-level name is defined, following imports."""
    for _ in range(MAX_DEPTH):
        if name in mod.assigns or name not in mod.imports:
            return (mod.name, name)
        source, original = mod.imports[name]
        mod, name = index.modules[source], original
    return (mod.name, name)


def _lookups(s: tuple) -> list[tuple]:
    """Every table lookup a shape may evaluate to (through conditions, ``or`` and rebinds)."""
    if s[0] == "lookup":
        return [s]
    if s[0] == "cond":
        return _lookups(s[2]) + _lookups(s[3])
    if s[0] == "alts":
        return [x for a in s[1] for x in _lookups(a)]
    if s[0] == "multi":
        return [x for a in s[2] for x in _lookups(a)]
    return []


# ---------------------------------------------------------------- harvesting


class Harvester:
    def __init__(self, index: Index) -> None:
        self.index = index
        self.out = Harvest()
        self._tables_done: set[tuple] = set()
        # (module, function) -> [((en param, index), (tr param, index)), ...]
        self._wrapper_keys: dict[tuple[str, str], list[tuple]] = {}
        self._tr_tables_used: set[TableRef] = set()

    # entry --------------------------------------------------------

    def run(self) -> Harvest:
        # pass 1: say() sites; parameters forwarded to say() make their function a wrapper
        for mod in self.index.having("say("):
            for scopes, call in _calls(mod.tree):
                if _is_say(call):
                    self._say_site(mod, scopes, call)
        # pass 2..: calls to wrappers (a wrapper may itself forward to a wrapper)
        handled: set[tuple] = set()  # (call, spec) already paired
        for _ in range(MAX_DEPTH):
            before = sum(map(len, self._wrapper_keys.values()))
            needles = sorted({f"{name}(" for _module, name in self._wrapper_keys})
            for mod in self.index.having(*needles) if needles else []:
                for scopes, call in _calls(mod.tree):
                    if _is_say(call):
                        continue
                    target = self._wrapper_for(mod, call)
                    if target is None:
                        continue
                    self._wrapper_call(mod, scopes, call, target, handled)
            if sum(map(len, self._wrapper_keys.values())) == before:
                break
        self._excluded_tables()
        return self.out

    # say() sites ---------------------------------------------------

    def _say_site(self, mod: Module, scopes: list[Scope], call: ast.Call) -> None:
        en, tr = _kw(call, "en"), _kw(call, "tr")
        if en is None or tr is None or call.args:
            self._skip(mod, call.lineno, "say() without en=/tr= keywords")
            return
        ctx = Ctx(self.index, mod, scopes)
        self._pair(mod, call.lineno, shape(en, ctx), shape(tr, ctx), "say", _dump(en))

    def _pair(self, mod: Module, line: int, es: tuple, ts: tuple, via: str, en_dump: str) -> None:
        # ``say(en=reason, tr=_REASON_TR.get(reason, reason))``: the table is keyed by English
        if ts[0] == "lookup" and ts[4] is None and ts[2] == en_dump:
            self._use_table(ts[1])
            self._table_english_keyed(ts[1])
            return
        if es[0] == "param" and ts[0] == "param" and es[1] is ts[1]:
            self._register_wrapper(mod, es[1], (es[2], es[3]), (ts[2], ts[3]), line)
            return
        if not self._pair_shapes(mod, line, es, ts, via):
            self._unpaired_tables(mod, line, es, ts, en_dump)

    def _pair_shapes(self, mod: Module, line: int, es: tuple, ts: tuple, via: str) -> bool:
        """Harvest what pairs up; False (and a skip) when the call does not pair at all."""
        if es[0] == "lit" and ts[0] == "lit":
            self._add_lit(mod, line, es, ts, via)
            return True
        if es[0] == "cond" and ts[0] == "cond":
            if es[1] != ts[1]:
                self._skip(mod, line, "en and tr conditions differ")
                return False
            branch = "conditional" if via == "say" else via
            ok_body = self._pair_shapes(mod, line, es[2], ts[2], branch)
            ok_else = self._pair_shapes(mod, line, es[3], ts[3], branch)
            return ok_body or ok_else
        if es[0] == "cond" and ts[0] == "lit":
            # the Turkish is the same either way: each English branch maps to it
            branch = "conditional" if via == "say" else via
            ok_body = self._pair_shapes(mod, line, es[2], ts, branch)
            ok_else = self._pair_shapes(mod, line, es[3], ts, branch)
            return ok_body or ok_else
        if es[0] == "lookup" and ts[0] == "lookup":
            return self._pair_lookups(mod, line, [es], ts, via)
        if es[0] == "alts" and ts[0] == "lookup":
            en_lookups = [a for a in es[1] if a[0] == "lookup"]
            if en_lookups:
                return self._pair_lookups(mod, line, en_lookups, ts, via)
        reason = _why(es, "en") or _why(ts, "tr") or f"en is {es[0]}, tr is {ts[0]}"
        self._skip(mod, line, reason)
        return False

    def _add_lit(self, mod: Module, line: int, es: tuple, ts: tuple, via: str) -> None:
        if not (isinstance(es[1], str) and isinstance(ts[1], str)):
            self._skip(mod, line, "en/tr resolve to non-text")
            return
        if not es[1]:
            self._skip(mod, line, "empty English text")
            return
        if via == "wrapper":
            kind = "wrapper"
        elif via == "conditional":
            kind = "conditional"
        else:
            kind = "literal" if es[2] is None and ts[2] is None else "constant_name"
        origin = ("names", es[2], ts[2]) if (es[2] or ts[2]) else ("say",)
        self._add(Pair(es[1], ts[1], kind, mod.rel, line, origin))

    def _pair_lookups(
        self, mod: Module, line: int, en_lookups: list[tuple], ts: tuple, via: str
    ) -> bool:
        if any(e[2] != ts[2] for e in en_lookups):
            self._skip(mod, line, "en and tr tables looked up with different keys")
            return False
        self._use_table(ts[1])
        if len(en_lookups) == 1 and en_lookups[0][1] == ts[1]:
            en_index, tr_index = en_lookups[0][4], ts[4]
            if en_index is None or tr_index is None or en_index == tr_index:
                self._skip(mod, line, "en and tr read the same table entry")
                return False
            self._table_pairs(ts[1], en_index, tr_index)
        elif ts[4] is None and all(e[1] != ts[1] for e in en_lookups):
            self._table_parallel([(e[1], e[4]) for e in en_lookups], ts[1])
        else:
            self._skip(mod, line, "table lookups of unsupported shape")
            return False
        en_default = en_lookups[0][3] if len(en_lookups) == 1 else None
        if en_default is not None and ts[3] is not None:
            if en_default[0] == "lit" and ts[3][0] == "lit":
                self._add_lit(mod, line, en_default, ts[3], via)
        return True

    def _unpaired_tables(self, mod: Module, line: int, es: tuple, ts: tuple, en_dump: str) -> None:
        """A table whose Turkish reaches this say() but whose English side does not resolve
        (``tr=turkish or english`` with ``turkish = _X_TR.get(code)`` rebound later)."""
        tr_tables = {lk[1] for lk in _lookups(ts)} - {lk[1] for lk in _lookups(es)}
        for ref in sorted(tr_tables, key=lambda r: (r.module, r.name)):
            self._use_table(ref)
            hits = [lk for lk in _lookups(ts) if lk[1] == ref]
            english_keyed = any(lk[2] == en_dump and lk[4] is None for lk in hits)
            if english_keyed:
                self._table_english_keyed(ref)
                continue
            self.out.unpaired_tables.append(
                {
                    "table": f"{ref.module}.{ref.name}",
                    "where": f"{mod.rel}:{line}",
                    "reason": "Turkish table reaches say() but its English side does not resolve",
                }
            )

    def _use_table(self, ref: TableRef) -> None:
        self._tr_tables_used.add(ref)

    # tables ---------------------------------------------------------

    def _table_english_keyed(self, ref: TableRef) -> None:
        if ("en", ref) in self._tables_done:
            return
        self._tables_done.add(("en", ref))
        mod = self.index.modules[ref.module]
        count = 0
        for key, value, line, problem in self.index.table_entries(ref):
            if problem:
                self._skip(mod, line, f"table {ref.name}: {problem}")
                continue
            if not (isinstance(key, str) and isinstance(value, str)):
                self._skip(mod, line, f"table {ref.name}: key or value not text")
                continue
            origin = ("table", ref.module, ref.name, key)
            self._add(Pair(key, value, "table_english_keyed", mod.rel, line, origin))
            count += 1
        self.out.tables[f"{ref.module}.{ref.name}"] = {
            "kind": "table_english_keyed",
            "pairs": count,
        }

    def _table_parallel(self, en_refs: list[tuple[TableRef, int | None]], tr_ref: TableRef) -> None:
        done_key = ("par", tuple(en_refs), tr_ref)
        if done_key in self._tables_done:
            return
        self._tables_done.add(done_key)
        tr_mod = self.index.modules[tr_ref.module]
        en_rows: dict[object, tuple[object, TableRef, int | None]] = {}
        en_lines: dict[object, tuple[Module, int]] = {}
        for en_ref, en_index in en_refs:
            en_mod = self.index.modules[en_ref.module]
            for key, value, line, problem in self.index.table_entries(en_ref):
                if problem:
                    self._skip(en_mod, line, f"table {en_ref.name}: {problem}")
                    continue
                if en_index is not None:
                    ok = isinstance(value, tuple) and -len(value) <= en_index < len(value)
                    value = value[en_index] if ok else None
                en_rows.setdefault(key, (value, en_ref, en_index))
                en_lines.setdefault(key, (en_mod, line))
        count = 0
        tr_keys = set()
        for key, value, line, problem in self.index.table_entries(tr_ref):
            if problem:
                self._skip(tr_mod, line, f"table {tr_ref.name}: {problem}")
                continue
            tr_keys.add(key)
            if key not in en_rows:
                self._skip(tr_mod, line, f"table {tr_ref.name}: key {key!r} has no English entry")
                continue
            en_text, en_ref, en_index = en_rows[key]
            if not (isinstance(en_text, str) and isinstance(value, str)):
                self._skip(tr_mod, line, f"table {tr_ref.name}: value not text")
                continue
            origin = (
                "parallel",
                tr_ref.module,
                tr_ref.name,
                en_ref.module,
                en_ref.name,
                en_index,
                key,
            )
            self._add(Pair(en_text, value, "table_parallel", tr_mod.rel, line, origin))
            count += 1
        for key, (en_mod, line) in en_lines.items():
            if key not in tr_keys:
                self._skip(en_mod, line, f"table {tr_ref.name}: key {key!r} has no Turkish entry")
        self.out.tables[f"{tr_ref.module}.{tr_ref.name}"] = {
            "kind": "table_parallel",
            "english_tables": [f"{r.module}.{r.name}" for r, _i in en_refs],
            "pairs": count,
        }

    def _table_pairs(self, ref: TableRef, en_index: int, tr_index: int) -> None:
        if ("pairs", ref, en_index, tr_index) in self._tables_done:
            return
        self._tables_done.add(("pairs", ref, en_index, tr_index))
        mod = self.index.modules[ref.module]
        count = 0
        for key, value, line, problem in self.index.table_entries(ref):
            if problem:
                self._skip(mod, line, f"table {ref.name}: {problem}")
                continue
            ok = isinstance(value, tuple) and len(value) > max(en_index, tr_index)
            if not ok or not (
                isinstance(value[en_index], str) and isinstance(value[tr_index], str)
            ):
                self._skip(mod, line, f"table {ref.name}: value is not an (en, tr) tuple")
                continue
            if not value[en_index]:
                self._skip(mod, line, "empty English text")
                continue
            origin = ("pairs", ref.module, ref.name, key, en_index, tr_index)
            self._add(Pair(value[en_index], value[tr_index], "table_pairs", mod.rel, line, origin))
            count += 1
        self.out.tables[f"{ref.module}.{ref.name}"] = {
            "kind": "table_pairs",
            "indexes": [en_index, tr_index],
            "pairs": count,
        }

    def _excluded_tables(self) -> None:
        """``*_TR`` dicts not used as a ``tr=`` side: listed for the reviewer, not harvested."""
        used = {f"{r.module}.{r.name}" for r in self._tr_tables_used}
        for mod in self.index.having("_TR"):
            for name, values in mod.assigns.items():
                if "TR" not in name.split("_") or len(values) != 1:
                    continue
                if _dict_node(values[0]) is None:
                    continue
                full = f"{mod.name}.{name}"
                if full in used or full in self.out.tables:
                    continue
                users = sorted(_name_users(mod).get(name, ()))
                self.out.excluded_tables.append(
                    {"table": full, "file": mod.rel, "line": values[0].lineno, "used_in": users}
                )

    # wrappers -------------------------------------------------------

    def _register_wrapper(
        self, mod: Module, scope: Scope, en_spec: tuple, tr_spec: tuple, line: int
    ) -> None:
        func = scope.func
        if isinstance(func, ast.Lambda) or mod.defs.get(func.name) is not func:
            self._skip(mod, line, "en/tr are parameters of a nested function or method")
            return
        specs = self._wrapper_keys.setdefault((mod.name, func.name), [])
        if (en_spec, tr_spec) in specs:
            return
        specs.append((en_spec, tr_spec))
        entry = self.out.wrappers.setdefault(
            f"{mod.name}.{func.name}",
            {"file": mod.rel, "line": func.lineno, "pairs": [], "calls": 0},
        )
        entry["pairs"].append({"en": list(en_spec), "tr": list(tr_spec)})

    def _wrapper_for(self, mod: Module, call: ast.Call) -> tuple[str, str] | None:
        if not isinstance(call.func, ast.Name):
            return None
        name = call.func.id
        if name in mod.defs:
            key = (mod.name, name)
        elif name in mod.imports:
            key = mod.imports[name]
        else:
            return None
        return key if key in self._wrapper_keys else None

    def _wrapper_call(
        self,
        mod: Module,
        scopes: list[Scope],
        call: ast.Call,
        target: tuple[str, str],
        handled: set[tuple],
    ) -> None:
        todo = [spec for spec in self._wrapper_keys[target] if (id(call), spec) not in handled]
        if not todo:
            return
        first = not any(h[0] == id(call) for h in handled)
        handled.update((id(call), spec) for spec in todo)
        func = self.index.modules[target[0]].defs[target[1]]
        positional = [a.arg for a in (*func.args.posonlyargs, *func.args.args)]
        defaults = dict(
            zip(positional[len(positional) - len(func.args.defaults) :], func.args.defaults)
        )
        defaults.update(
            {
                a.arg: d
                for a, d in zip(func.args.kwonlyargs, func.args.kw_defaults, strict=True)
                if d is not None
            }
        )
        if first:
            self.out.wrappers[f"{target[0]}.{target[1]}"]["calls"] += 1
        if any(isinstance(a, ast.Starred) for a in call.args) or any(
            k.arg is None for k in call.keywords
        ):
            self._skip(mod, call.lineno, f"call to wrapper {target[1]}() with *args/**kwargs")
            return

        def arg(spec: tuple) -> tuple:
            param, index = spec
            node = _kw(call, param)
            ctx = Ctx(self.index, mod, scopes)
            if node is None and param in positional and positional.index(param) < len(call.args):
                node = call.args[positional.index(param)]
            if node is None and param in defaults:
                node, ctx = defaults[param], Ctx(self.index, self.index.modules[target[0]], [])
            if node is None:
                return ("unknown", f"no argument for {param}")
            got = shape(node, ctx)
            return got if index is None else _index(got, index)

        for en_spec, tr_spec in todo:
            es, ts = arg(en_spec), arg(tr_spec)
            if es[0] == "unknown" and es[1] == "constant NoneType":
                continue  # an optional pair left out (``description=None``)
            if es[0] == "param" and ts[0] == "param" and es[1] is ts[1]:
                self._register_wrapper(mod, es[1], (es[2], es[3]), (ts[2], ts[3]), call.lineno)
                continue
            if not self._pair_shapes(mod, call.lineno, es, ts, "wrapper"):
                self._unpaired_tables(mod, call.lineno, es, ts, "")

    # bookkeeping ----------------------------------------------------

    def _add(self, pair: Pair) -> None:
        self.out.pairs.append(pair)

    def _skip(self, mod: Module, line: int, reason: str, detail: str = "") -> None:
        self.out.skipped.append(Skip(mod.rel, line, reason, detail))


_USERS: dict[int, dict[str, set[str]]] = {}


def _name_users(mod: Module) -> dict[str, set[str]]:
    """name -> functions that read it, for one module (cached)."""
    if id(mod.tree) not in _USERS:
        users: dict[str, set[str]] = defaultdict(set)
        for func in ast.walk(mod.tree):
            if isinstance(func, ast.FunctionDef | ast.AsyncFunctionDef):
                for node in _own_nodes(func):
                    if isinstance(node, ast.Name):
                        users[node.id].add(func.name)
        _USERS[id(mod.tree)] = users
    return _USERS[id(mod.tree)]


def _why(s: tuple, side: str) -> str | None:
    if s[0] == "unknown":
        return f"{side}: {s[1]}"
    if s[0] == "param":
        return f"{side}: parameter {s[2]} not forwarded as a wrapper pair"
    if s[0] == "cond":
        return _why(s[2], side) or _why(s[3], side)
    if s[0] == "alts":
        for alt in s[1]:
            if (why := _why(alt, side)) is not None:
                return why
    if s[0] == "multi":
        return f"{side}: {s[1]}"
    return None


def _calls(tree: ast.Module) -> Iterable[tuple[list[Scope], ast.Call]]:
    """Every call with the function scopes around it (outermost first)."""
    out: list[tuple[list[Scope], ast.Call]] = []

    def visit(node: ast.AST, scopes: list[Scope]) -> None:
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.FunctionDef | ast.AsyncFunctionDef | ast.Lambda):
                visit(child, [*scopes, Scope(child)])
                continue
            if isinstance(child, ast.Call):
                out.append((scopes, child))
            visit(child, scopes)

    visit(tree, [])
    return out


# ---------------------------------------------------------------- Turkish outside say()


def turkish_branches(index: Index) -> list[dict]:
    """``== "tr"`` / ``language == "tr"`` comparisons outside ``say()``: Turkish copy picked
    without ``say``, which a catalog language (German) will not cover."""
    found = []
    for mod in index.having('"tr"', "'tr'"):
        inside: set[int] = set()
        for node in ast.walk(mod.tree):
            if _is_say(node):
                inside.update(id(sub) for sub in ast.walk(node))
        funcs: list[tuple[int, int, str]] = [
            (n.lineno, n.end_lineno or n.lineno, n.name)
            for n in ast.walk(mod.tree)
            if isinstance(n, ast.FunctionDef | ast.AsyncFunctionDef)
        ]
        for node in ast.walk(mod.tree):
            if not isinstance(node, ast.Compare) or id(node) in inside:
                continue
            if not _compares_tr(node):
                continue
            enclosing = [f for f in funcs if f[0] <= node.lineno <= f[1]]
            func = max(enclosing, key=lambda f: f[0])[2] if enclosing else None
            found.append(
                {
                    "file": mod.rel,
                    "line": node.lineno,
                    "function": func,
                    "code": ast.unparse(node)[:120],
                }
            )
    return sorted(found, key=lambda r: (r["file"], r["line"]))


def _compares_tr(node: ast.Compare) -> bool:
    operands = [node.left, *node.comparators]
    for op, right in zip(node.ops, node.comparators, strict=True):
        if isinstance(op, ast.Eq | ast.NotEq) and any(
            isinstance(o, ast.Constant) and o.value == "tr" for o in operands
        ):
            return True
        if isinstance(op, ast.In | ast.NotIn) and isinstance(right, ast.Tuple | ast.List | ast.Set):
            if any(isinstance(e, ast.Constant) and e.value == "tr" for e in right.elts):
                return True
    return False


# ---------------------------------------------------------------- api


def app_sources(root: Path = APP) -> dict[str, str]:
    return {
        str(path.relative_to(API)): path.read_text(encoding="utf-8")
        for path in sorted(root.rglob("*.py"))
    }


def harvest(sources: Mapping[str, str]) -> Harvest:
    return Harvester(Index(sources)).run()


def render_catalog(messages: Mapping[str, str]) -> str:
    data = {"source": SOURCE_NOTE, "messages": dict(sorted(messages.items()))}
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def render_conflicts(conflicts: Mapping[str, list[dict]]) -> str:
    data = {
        "source": SOURCE_NOTE,
        "note": (
            "Same English key, different Turkish text in different places. tr.json keeps the "
            "first in file:line order; a catalog language gets one translation per key."
        ),
        "conflicts": dict(sorted(conflicts.items())),
    }
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def report(result: Harvest, sources: Mapping[str, str]) -> dict:
    messages, conflicts = result.messages()
    by_kind = Counter(p.kind for p in result.pairs)
    skipped_by_reason = Counter(_reason_family(s.reason) for s in result.skipped)
    branches = turkish_branches(Index(sources))  # a fresh index: cheap, parses lazily
    return {
        "pairs_by_kind": {k: by_kind.get(k, 0) for k in KINDS},
        "pairs_total": len(result.pairs),
        "keys": len(messages),
        "conflicts": len(conflicts),
        "skipped_total": len(result.skipped),
        "skipped_by_reason": dict(skipped_by_reason.most_common()),
        "skipped": [
            {"where": f"{s.file}:{s.line}", "reason": s.reason}
            for s in sorted(result.skipped, key=lambda s: (s.file, s.line, s.reason))
        ],
        "tables": dict(sorted(result.tables.items())),
        "excluded_tables": result.excluded_tables,
        "unpaired_tables": result.unpaired_tables,
        "wrappers": dict(sorted(result.wrappers.items())),
        "turkish_outside_say_count": len(branches),
        "turkish_outside_say_by_file": dict(Counter(b["file"] for b in branches).most_common()),
        "turkish_outside_say": branches,
    }


def _reason_family(reason: str) -> str:
    """A reason with its names taken out, for the counts ("table _X: key 'a' ..." -> "table _")."""
    reason = re.sub(r"'[^']*'|\"[^\"]*\"", "_", reason)
    return re.sub(
        r"\b(name|parameter|table|key|call|wrapper|from|of|into) [^\s:]+", r"\1 _", reason
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when tr.json is stale")
    parser.add_argument("--report", type=Path, help="write the harvest report JSON here")
    args = parser.parse_args()
    sources = app_sources()
    result = harvest(sources)
    messages, conflicts = result.messages()
    catalog_text = render_catalog(messages)
    conflicts_text = render_conflicts(conflicts)
    if args.report:
        data = report(result, sources)
        args.report.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", "utf-8")
    if args.check:
        stale = [
            path.relative_to(REPO)
            for path, text in ((TR_JSON, catalog_text), (CONFLICTS_JSON, conflicts_text))
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            names = ", ".join(str(p) for p in stale)
            print(
                f"stale: {names}. Run python3 scripts/kria/build_copy_catalog.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok: {len(messages)} keys, {len(conflicts)} conflicts")
        return 0
    COPY_DIR.mkdir(parents=True, exist_ok=True)
    TR_JSON.write_text(catalog_text, encoding="utf-8")
    CONFLICTS_JSON.write_text(conflicts_text, encoding="utf-8")
    by_kind = Counter(p.kind for p in result.pairs)
    print(
        json.dumps(
            {
                "keys": len(messages),
                "conflicts": len(conflicts),
                "pairs_by_kind": dict(by_kind),
                "skipped": len(result.skipped),
            },
            ensure_ascii=False,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
