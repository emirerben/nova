#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(path.join(root, 'src/apps/web/package.json'));
const ts = require('typescript');
const source = path.join(root, 'src/packages/motion-runtime');
const names = ['contract', 'catalog', 'limits', 'presets', 'evolving-type', 'canvaskit', 'native-command-canvas'];
const modules = names.map(name => {
  const result = ts.transpileModule(fs.readFileSync(path.join(source, 'src', name+'.ts'), 'utf8'), {
    compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true},
  });
  return `${JSON.stringify(name+'.ts')}: function(exports, require) {\n${result.outputText}\n}`;
});
for (const name of ['creator-blocks.catalog.json', 'motion-limits.json']) {
  modules.push(`${JSON.stringify(name)}: function(exports) { Object.assign(exports, ${fs.readFileSync(path.join(source, name), 'utf8')}); }`);
}
const output = `// Generated by scripts/ios/generate-motion-runtime.mjs. Do not edit.\nvar NativeMotionRuntime = (function() {\nconst modules = {${modules.join(',\n')}};\nconst cache = {};\nfunction require(name) { const key = name.split('/').pop(); if (!cache[key]) { const exports = {}; cache[key] = exports; if (!modules[key]) throw new Error('Unknown bundled module '+key); modules[key](exports, require); } return cache[key]; }\nreturn require('native-command-canvas.ts');\n})();\n`;
const target = path.join(root, 'src/apps/ios/Packages/KriaMediaEngine/Sources/KriaMediaEngine/Resources/NativeMotionRuntime.generated.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) { console.error('Native motion runtime is stale'); process.exit(1); }
} else fs.writeFileSync(target, output);
