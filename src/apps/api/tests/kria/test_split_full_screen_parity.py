"""Cross-platform parity of "Full screen from / until playhead" (KRI-1394).

The iPhone editor plans the cut itself (``NativeEditorSession.splitFullScreenResult``); chat runs
the server port (``app/kria/split_full_screen.py``). The shared file
``tests/fixtures/split_full_screen.json`` is GENERATED by running the server planner on each case;
this test asserts the file still equals the server's output, and
``NativeSplitFullScreenParityTests`` (iOS) asserts the Swift planner against the same file.

Ways the two could disagree, each a case below:

* the wrong panel goes full screen (selected panel, no selection, a selected panel with no
  footage on that side);
* a clip is lost or a frame counted twice at the cut, or the cut part's source window is not
  advanced (plain, played at 2x, a derived rate, a held frame);
* a gap in the panel shortens the video instead of being filled by the clip before it, or by the
  first clip reaching back;
* footage that runs out (stored length, the file's measured length, or neither known) keeps
  time it cannot fill, and the lanes after it stay behind or a lane over it survives;
* a photo grows like a video or keeps a parent link;
* a crossfade between full-screen clips is kept where it cannot replay, or cut where it can;
* the clip before the section keeps a transition into the full-screen clips (until side);
* a collapsing section keeps its old length;
* the phone refuses (within 0.5 s of an edge, nothing left in the split, the playhead in
  another section) and the server plans anyway, or the reverse.

Regenerate after a deliberate planner change::

    cd src/apps/api && .venv/bin/python -m tests.kria.test_split_full_screen_parity
"""

