def _member(
    slot_id: str,
    panel: int,
    offset: float,
    duration: float,
    *,
    in_s: float = 0.0,
    clip_index: int = 0,
    section: str = "s",
    **raw: Any,
) -> dict[str, Any]:
    row = {
        "slot_id": slot_id,
        "clip_index": clip_index,
        "in_s": in_s,
        "duration_s": duration,
        "transition_after": "cut",
        "split_section_id": section,
        "split_panel_index": panel,
        "split_offset_s": offset,
        "source_duration_s": 30.0,
    }
    row.update(raw)
    return {key: value for key, value in row.items() if value is not None}


def _ordinary(
    slot_id: str,
    duration: float,
    *,
    clip_index: int = 0,
    transition: str = "cut",
    transition_s: float | None = None,
) -> dict[str, Any]:
    row = {
        "slot_id": slot_id,
        "clip_index": clip_index,
        "in_s": 0.0,
        "duration_s": duration,
        "transition_after": transition,
        "source_duration_s": 30.0,
    }
    if transition_s is not None:
        row["transition_duration_s"] = transition_s
    return row


def _section(
    duration: float, panels: int = 2, *, section_id: str = "s", collapse: bool = False
) -> dict[str, Any]:
    row = {
        "id": section_id,
        "duration_s": duration,
        "panel_count": panels,
        "panel_weights": [1.0] * panels,
        "gutter": 0.0,
        "background_color": "#000000",
    }
    if collapse:
        row["collapse_empty_panels"] = True
    return row


def _harbour(
    *, bottom_second: dict[str, Any] | None = None, bottom_second_in: float = 2.0
) -> list[dict[str, Any]]:
    """lead 0-1, a fixed 6 s section (top: one clip; bottom: 0-2 and 3-5), tail 7-9."""
