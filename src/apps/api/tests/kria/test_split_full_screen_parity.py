def _canonical_slots(rows: list[dict[str, Any]], known: set[str]) -> list[dict[str, Any]]:
    names: dict[str, str] = {}
    counter = itertools.count(1)

    def name(value: Any) -> Any:
        if not isinstance(value, str) or value in known:
            return value
        if value not in names:
            names[value] = f"new-{next(counter)}"
        return names[value]

    out = []
    for row in rows:
        item: dict[str, Any] = {}
        for key in SLOT_KEYS:
            value = row.get(key)
            if value is None or (key == "removed" and value is False):
                continue
            item[key] = name(value) if key in ("slot_id", "parent_segment_id") else value
        item.setdefault("transition_after", "cut")
        out.append(item)
    return out


def _canonical_lanes(lanes: dict[str, list[dict[str, Any]]]) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {}
    for key in LANE_KEYS:
        rows = []
        for row in lanes.get(key) or []:
            item = {k: row[k] for k in ("id", "at_s", "start_s", "end_s") if k in row}
            if key == "sound_effects" and "at_s" in item:
                item = {"id": item["id"], "at_s": item["at_s"]}
            if row.get("words"):
                item["words"] = [
                    {"start_s": w["start_s"], "end_s": w["end_s"]} for w in row["words"]
                ]
            rows.append(item)
        out[key] = rows
    return out


def expected_for(case: dict[str, Any]) -> dict[str, Any] | None:
    plan = plan_split_full_screen(
        copy.deepcopy(case["slots"]),
        copy.deepcopy(case["sections"]),
        section_id=case["section_id"],
        playhead_s=case["playhead_s"],
        side=case["side"],
        selected_panel=case["selected_panel"],
        measured={int(k): v for k, v in case["sources"].items()},
        stills=(),
    )
    if plan is None:
        return None
    lanes = case["lanes"]
    moved = remove_time(
        Lanes(
            captions=copy.deepcopy(lanes.get("caption_cues") or []),
            sound_effects=copy.deepcopy(lanes.get("sound_effects") or []),
            media_overlays=copy.deepcopy(lanes.get("media_overlays") or []),
            visual_blocks=[],
            camera_effects=[],
            drawings=[],
            speaker_background=None,
        ),
        plan.lost,
    )
    known = {row["slot_id"] for row in case["slots"]}
    return {
        "panel": plan.panel,
        "slots": _canonical_slots(plan.slots, known),
        "split_screen_sections": [
            {"id": s["id"], "duration_s": s["duration_s"]} for s in plan.sections
        ],
        "lanes": _canonical_lanes(
            {
                "caption_cues": moved.captions,
                "sound_effects": moved.sound_effects,
                "media_overlays": moved.media_overlays,
            }
        )
        if lanes
        else {},
    }


def build_fixture() -> dict[str, Any]:
    cases = []
    for case in _cases():
        cases.append(
            {
                "name": case["name"],
                "section_id": case["section_id"],
                "playhead_s": case["playhead_s"],
                "side": case["side"],
                "selected_panel": case["selected_panel"],
                "sources": [
                    {"clip_index": int(index), "duration_s": length}
                    for index, length in sorted(case["sources"].items())
                ],
                "slots": case["slots"],
                "split_screen_sections": case["sections"],
                "lanes": case["lanes"],
                "expected": expected_for(case),
            }
        )
    return {
        "description": (
            "Full screen from / until playhead on a split section (KRI-1394). Generated by "
            "tests/kria/test_split_full_screen_parity.py from the server planner; "
            "NativeSplitFullScreenParityTests asserts the iPhone planner against it. New slot ids "
            "are named new-1, new-2, ... in the order they appear."
        ),
        "tolerance_s": TOLERANCE_S,
        "slot_keys": list(SLOT_KEYS),
        "cases": cases,
    }


def _close(a: Any, b: Any) -> bool:
    if isinstance(a, bool) or isinstance(b, bool):
        return a == b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(a - b) <= TOLERANCE_S
    if isinstance(a, dict) and isinstance(b, dict):
        return a.keys() == b.keys() and all(_close(a[k], b[k]) for k in a)
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(_close(x, y) for x, y in zip(a, b, strict=True))
    return a == b


def test_fixture_is_the_server_planner_output() -> None:
    stored = json.loads(FIXTURE.read_text(encoding="utf-8"))
    fresh = json.loads(json.dumps(build_fixture()))
    assert [c["name"] for c in stored["cases"]] == [c["name"] for c in fresh["cases"]]
    for old, new in zip(stored["cases"], fresh["cases"], strict=True):
        assert _close(old, new), (
            f"{old['name']}: the server planner no longer gives the shared answer; regenerate "
            "with `python -m tests.kria.test_split_full_screen_parity` only for a deliberate "
            "change and run NativeSplitFullScreenParityTests"
        )


@pytest.mark.parametrize(
    "name",
    [c["name"] for c in _cases() if c["name"].startswith("refused_")],
)
def test_refused_cases_plan_nothing(name: str) -> None:
    case = next(c for c in _cases() if c["name"] == name)
    assert expected_for(case) is None


def test_planned_cases_keep_the_video_length_unless_footage_ran_out() -> None:
    from app.kria.split_screen import layout_split_timeline

    for case in _cases():
        plan = plan_split_full_screen(
            copy.deepcopy(case["slots"]),
            copy.deepcopy(case["sections"]),
            section_id=case["section_id"],
            playhead_s=case["playhead_s"],
            side=case["side"],
            selected_panel=case["selected_panel"],
            measured=case["sources"],
        )
        if plan is None:
            continue
        before = layout_split_timeline(case["slots"], case["sections"])[2]
        after = layout_split_timeline(plan.slots, plan.sections)[2]
        lost = sum(b - a for a, b in plan.lost)
        assert abs(before - lost - after) < 1e-3, case["name"]
        ids = [row["slot_id"] for row in plan.slots]
        assert len(set(ids)) == len(ids), f"{case['name']}: an occurrence is counted twice"


