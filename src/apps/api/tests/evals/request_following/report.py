"""KPI report for the request-following eval.

    cd src/apps/api
    python -m tests.evals.request_following.report --phase baseline \\
        --out ../../../docs/reviews/kri-185/request-following-baseline.md

Replay mode only (offline, deterministic — no clock in the output, so the file diffs cleanly
when a phase moves a number). One report per phase P0..P5 is published by P6b.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .models import REQUEST_TYPES, RFFixture, ThreadResult
from .runner import (
    discover_fixture_paths,
    load_fixture,
    load_footage,
    run_thread,
    score_reference,
)
from .scorer import KPIReport, compute_kpi, wrong_landmark_rate


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.0%}"


def collect() -> tuple[list[tuple[RFFixture, ThreadResult]], list[tuple[RFFixture, ThreadResult]]]:
    """(replayed threads, reference self-checks for authored threads)."""
    replayed: list[tuple[RFFixture, ThreadResult]] = []
    references: list[tuple[RFFixture, ThreadResult]] = []
    for path in discover_fixture_paths():
        fixture = load_fixture(path)
        replayed.append((fixture, run_thread(fixture)))
        if fixture.reference is not None:
            references.append((fixture, score_reference(fixture)))
    return replayed, references


def render_report(phase: str = "baseline") -> str:
    replayed, references = collect()
    kpi: KPIReport = compute_kpi(result for _, result in replayed)
    lines = [
        f"# Request-following KPI: {phase}",
        "",
        "Share of creator requirements the finished edit actually met (strict: `partial` does "
        "not count). Generated by `python -m tests.evals.request_following.report`; "
        "replay mode, offline.",
        "",
        "## Headline",
        "",
        f"- **Requirements met: {_pct(kpi.met_share)}** "
        f"({kpi.overall.met}/{kpi.overall.total}; partial {kpi.overall.partial}, "
        f"unmet {kpi.overall.unmet})",
        f"- Replies that overclaimed (talked as if a requirement was handled when it was not, "
        f"with no 'not done' marker): **{kpi.overall.overclaims}**",
        f"- Threads measured from recordings: {kpi.threads_scored}. Authored threads awaiting "
        f"recordings (not in the KPI): {kpi.threads_unrecorded}.",
        "- Small-sample warning: until authored threads are recorded (P6b), the KPI is the "
        "East Run thread alone. Read it as a trend line per phase, not as a rate.",
        "",
        "## By request type",
        "",
        "| Request type | Requirements | Met | Partial | Unmet | Met share | Overclaims |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for request_type in REQUEST_TYPES:
        row = kpi.by_type.get(request_type)
        if row is None:
            lines.append(f"| {request_type} | 0 | | | | not measured | |")
            continue
        lines.append(
            f"| {request_type} | {row.total} | {row.met} | {row.partial} | {row.unmet} | "
            f"{_pct(row.met_share)} | {row.overclaims} |"
        )

    for fixture, result in replayed:
        if result.unrecorded:
            continue
        lines += [
            "",
            f"## {fixture.fixture_id} ({fixture.provenance})",
            "",
            fixture.description,
            "",
        ]
        lines += [
            "| Requirement | Type | Status | Why | Reply overclaims |",
            "|---|---|---|---|---|",
        ]
        for item in result.scores:
            lines.append(
                f"| {item.requirement_id} | {item.request_type} | {item.status} | "
                f"{item.reason} | {'yes' if item.reply_overclaims else ''} |"
            )
        lines += ["", "Turns:", ""]
        for spec, turn in zip(fixture.turns, result.turns, strict=True):
            reply = turn.reply if turn.reply is not None else "(no reply recorded)"
            lines.append(
                f"- `{turn.turn_id}` ({turn.engine}) asked: {spec.user_message!r} -> {reply!r}"
            )

    lines += [
        "",
        "## Authored fixtures (checker self-check)",
        "",
        "Each authored brief carries a hand-built reference edit. It must score `met` on every "
        "requirement, otherwise the checker cannot be trusted. These are not measurements of the "
        "current system.",
        "",
        "| Fixture | Requirements | Reference met | Recorded outcome |",
        "|---|---:|---:|---|",
    ]
    for (fixture, ref), (_, replay) in zip(
        references, [r for r in replayed if r[0].reference], strict=True
    ):
        met = sum(1 for s in ref.scores if s.status == "met")
        state = "awaiting recording" if replay.unrecorded else "recorded"
        lines.append(
            f"| {fixture.fixture_id} | {len(ref.scores)} | {met}/{len(ref.scores)} | {state} |"
        )

    rates = []
    for footage_id in sorted({f.footage for f, _ in replayed}):
        rate, judged = wrong_landmark_rate(load_footage(footage_id))
        rates.append((footage_id, rate, judged))
    lines += [
        "",
        "## Wrong-landmark rate",
        "",
        "Share of *inferred* landmark guesses that name the wrong place (D4 accepts best-guess "
        "names, so guess quality is measured). Stub until P3 supplies inferred landmark facts.",
        "",
        "| Footage | Rate | Guesses judged |",
        "|---|---:|---:|",
    ]
    lines += [f"| {fid} | {_pct(rate)} | {judged} |" for fid, rate, judged in rates]
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--phase", default="baseline", help="label for the report title")
    parser.add_argument("--out", type=Path, default=None, help="write here instead of stdout")
    args = parser.parse_args()
    text = render_report(args.phase)
    if args.out is None:
        print(text)
    else:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
