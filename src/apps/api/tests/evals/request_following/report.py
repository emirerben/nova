"""KPI report for the request-following eval.

    cd src/apps/api
    python -m tests.evals.request_following.report --phase baseline \\
        --out ../../../docs/reviews/kri-185/request-following-baseline.md

Replay mode is the default (offline, deterministic — no clock in the output, so the file
diffs cleanly when a phase moves a number). One report per phase P0..P5 is published by P6b.

`--eval-mode live` swaps the recorded model text of every `v1_copilot` turn for a real Gemini
call. It is opt-in, paid, and refuses to start without the same guards the pytest live evals
use (`--usage-purpose`, `--test-run-id`, `--max-cost-usd` <= $2, `--approve-reservation`) plus
`GEMINI_API_KEY`. The committed baseline is always a replay report.

    NOVA_EVAL_MODE=live python -m tests.evals.request_following.report --phase P5 \\
        --eval-mode live --usage-purpose live_eval --test-run-id rf-p5-<date> \\
        --max-cost-usd 1 --approve-reservation
"""

from __future__ import annotations

import argparse
import math
import os
from pathlib import Path

from .models import REQUEST_TYPES, RFFixture, ThreadResult
from .runner import (
    Mode,
    discover_fixture_paths,
    load_fixture,
    load_footage,
    run_thread,
    score_reference,
)
from .scorer import KPIReport, compute_kpi, wrong_landmark_rate


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.0%}"


LIVE_COST_CAP_USD = 2.0
ACTION_PREFIX = "action_"


def _percentile(values: list[float], share: float) -> float:
    """Nearest-rank percentile: the smallest value at or above `share` of the sample."""
    ordered = sorted(values)
    return ordered[max(0, math.ceil(share * len(ordered)) - 1)]


def _recorded_calls(fixtures: list[RFFixture]) -> list[dict]:
    return [
        t.copilot
        for f in fixtures
        for t in f.turns
        if t.engine == "v1_copilot" and "raw_text" in (t.copilot or {})
    ]


def collect(
    mode: Mode = "replay",
) -> tuple[list[tuple[RFFixture, ThreadResult]], list[tuple[RFFixture, ThreadResult]]]:
    """(replayed threads, reference self-checks for authored threads)."""
    replayed: list[tuple[RFFixture, ThreadResult]] = []
    references: list[tuple[RFFixture, ThreadResult]] = []
    for path in discover_fixture_paths():
        fixture = load_fixture(path)
        # Executable cassettes are regression evidence, not part of the historical
        # recorded KPI until a separately reviewed live/DB-backed capture exists.
        if fixture.provenance == "authored" and any(
            (turn.kria or {}).get("cassette") or (turn.kria or {}).get("strategy_cassette")
            for turn in fixture.turns
        ):
            continue
        replayed.append((fixture, run_thread(fixture, mode=mode)))
        if fixture.reference is not None:
            references.append((fixture, score_reference(fixture)))
    return replayed, references


def render_report(phase: str = "baseline", mode: Mode = "replay") -> str:
    replayed, references = collect(mode)
    kpi: KPIReport = compute_kpi(result for _, result in replayed)
    how = (
        "replay mode, offline."
        if mode == "replay"
        else "LIVE mode: every v1_copilot turn called a real model (not a recording)."
    )
    threads = [(f, r) for f, r in replayed if not f.fixture_id.startswith(ACTION_PREFIX)]
    actions = [(f, r) for f, r in replayed if f.fixture_id.startswith(ACTION_PREFIX)]
    kpi_threads = compute_kpi(r for _, r in threads)
    kpi_actions = compute_kpi(r for _, r in actions)
    calls = [c for c in _recorded_calls([f for f, _ in replayed]) if c.get("latency_s") is not None]
    latency = [float(c["latency_s"]) for c in calls]
    models = sorted({str(c["model_actual"]) for c in calls if c.get("model_actual")})
    versions = sorted({str(c["prompt_version"]) for c in calls if c.get("prompt_version")})
    lines = [
        f"# Request-following KPI: {phase}",
        "",
        "Share of creator requirements the finished edit actually met (strict: `partial` does "
        "not count). Generated by `python -m tests.evals.request_following.report`; " + how,
        "",
        "## Headline",
        "",
        f"- **Requirements met: {_pct(kpi.met_share)}** "
        f"({kpi.overall.met}/{kpi.overall.total}; partial {kpi.overall.partial}, "
        f"unmet {kpi.overall.unmet}), over every recorded thread and the per-action set.",
        f"- **Replies that overclaimed: {kpi.overall.overclaims}** (a requirement was missed and "
        "the reply never said so: where the requirement names claim terms, the reply names one; "
        "otherwise the turn applied ops and the reply has no 'not done' marker. A turn that "
        "applied nothing claims nothing).",
    ]
    if latency:
        lines.append(
            f"- **Turn time: p50 {_percentile(latency, 0.5):.1f}s, p95 "
            f"{_percentile(latency, 0.95):.1f}s** over {len(latency)} recorded copilot calls "
            "(wall time of the live model call, retries included; planner routing, queueing "
            "and render are not in it)."
        )
    lines += [
        "",
        "| Set | Threads | Requirements | Met | Partial | Unmet | Met share | Overclaims |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
        f"| Conversation threads | {kpi_threads.threads_scored} | {kpi_threads.overall.total} | "
        f"{kpi_threads.overall.met} | {kpi_threads.overall.partial} | "
        f"{kpi_threads.overall.unmet} | {_pct(kpi_threads.met_share)} | "
        f"{kpi_threads.overall.overclaims} |",
        f"| Per-action set | {kpi_actions.threads_scored} | {kpi_actions.overall.total} | "
        f"{kpi_actions.overall.met} | {kpi_actions.overall.partial} | "
        f"{kpi_actions.overall.unmet} | {_pct(kpi_actions.met_share)} | "
        f"{kpi_actions.overall.overclaims} |",
        "",
        f"Threads measured from recordings: {kpi.threads_scored}. Threads awaiting recordings "
        f"(not in the KPI): {kpi.threads_unrecorded}.",
        "",
        "## Provenance",
        "",
        f"- Recorded model: {', '.join(models) or 'none'}.",
        f"- Prompt version of the recordings: {', '.join(versions) or 'none'}.",
        "- Measured path: `EditCopilotAgent` -> `_honest_outcome` -> `compile_editor_ops` "
        "(`runner.replay_v1_copilot`). The planner's routing in front of the copilot and the "
        "repair retry behind it are not in this path, and nothing was rendered.",
        "- Snapshots are built by the real `build_editor_snapshot` over a synthetic phone "
        "(`render_destination: device`) variant, with the clip facts the chat path hands the "
        "copilot. Footage is synthetic (invented places only).",
        "",
        "## By request type",
        "",
        "| Request type | Requirements | Met | Partial | Unmet | Met share | Overclaims |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for request_type in REQUEST_TYPES:
        row = kpi.by_type.get(request_type)
        if row is None:
            lines.append(f"| {request_type} | 0 | | | | not measured | |")
            continue
        lines.append(
            f"| {request_type} | {row.total} | {row.met} | {row.partial} | {row.unmet} | "
            f"{_pct(row.met_share)} | {row.overclaims} |"
        )

    lines += [
        "",
        "## Per-action set (one plain request per `agent_ops` parity group, phone snapshot)",
        "",
        "`Reference` is what the real parser and compiler do with a hand-written op for the "
        "request on the real variant: `reaches` (parses and compiles), `blocked at parse` or "
        "`blocked at compile`. A blocked group cannot be met by any model today.",
        "",
        "| Thread | Request | Reference | Model emitted | Status | Why |",
        "|---|---|---|---|---|---|",
    ]
    for fixture, result in actions:
        probe = fixture.reference_probe or {}
        if not probe.get("parsed_ops"):
            reach = "blocked at parse"
        elif probe.get("compiles") is True:
            reach = "reaches"
        else:
            reach = "blocked at compile"
        emitted = [op.get("op") for turn in result.turns for op in turn.parsed_ops] or "no op"
        score_row = result.scores[0] if result.scores else None
        lines.append(
            f"| {fixture.fixture_id} | {fixture.turns[0].user_message} | {reach} | {emitted} | "
            f"{score_row.status if score_row else 'unrecorded'} | "
            f"{score_row.reason if score_row else ''} |"
        )

    for fixture, result in threads:
        if result.unrecorded:
            continue
        lines += [
            "",
            f"## {fixture.fixture_id} ({fixture.provenance})",
            "",
            fixture.description,
            "",
        ]
        lines += [
            "| Requirement | Type | Status | Why | Reply overclaims |",
            "|---|---|---|---|---|",
        ]
        for item in result.scores:
            lines.append(
                f"| {item.requirement_id} | {item.request_type} | {item.status} | "
                f"{item.reason} | {'yes' if item.reply_overclaims else ''} |"
            )
        lines += ["", "Turns:", ""]
        for spec, turn in zip(fixture.turns, result.turns, strict=True):
            reply = turn.reply if turn.reply is not None else "(no reply recorded)"
            lines.append(
                f"- `{turn.turn_id}` ({turn.engine}) asked: {spec.user_message!r} -> {reply!r}"
            )

    lines += [
        "",
        "## Authored fixtures (checker self-check)",
        "",
        "Each authored brief carries a hand-built reference edit. It must score `met` on every "
        "requirement, otherwise the checker cannot be trusted. These are not measurements of the "
        "current system.",
        "",
        "| Fixture | Requirements | Reference met | Recorded outcome |",
        "|---|---:|---:|---|",
    ]
    for (fixture, ref), (_, replay) in zip(
        references, [r for r in replayed if r[0].reference], strict=True
    ):
        if fixture.fixture_id.startswith(ACTION_PREFIX):
            continue
        met = sum(1 for s in ref.scores if s.status == "met")
        state = "awaiting recording" if replay.unrecorded else "recorded"
        lines.append(
            f"| {fixture.fixture_id} | {len(ref.scores)} | {met}/{len(ref.scores)} | {state} |"
        )

    rates = []
    for footage_id in sorted({f.footage for f, _ in replayed}):
        rate, judged = wrong_landmark_rate(load_footage(footage_id))
        rates.append((footage_id, rate, judged))
    lines += [
        "",
        "## Wrong-landmark rate",
        "",
        "Share of *inferred* landmark guesses that name the wrong place (D4 accepts best-guess "
        "names, so guess quality is measured). The guesses are the synthetic footage's recorded "
        "`inferred` landmark facts scored against each clip's `true_landmark`; a live "
        "`landmark_guess` run is scored with `scorer.wrong_landmark_rate(footage, guesses)`.",
        "",
        "| Footage | Rate | Guesses judged |",
        "|---|---:|---:|",
    ]
    lines += [f"| {fid} | {_pct(rate)} | {judged} |" for fid, rate, judged in rates]
    lines.append("")
    return "\n".join(lines)


def _require_live_guards(args: argparse.Namespace, parser: argparse.ArgumentParser) -> None:
    """Same contract as the pytest live evals: purpose + run id + capped approval, or refuse."""
    if not (args.usage_purpose and args.test_run_id and args.approve_reservation):
        parser.error(
            "--eval-mode live needs --usage-purpose, --test-run-id, --max-cost-usd and "
            "--approve-reservation"
        )
    if args.max_cost_usd is None or not 0 < args.max_cost_usd <= LIVE_COST_CAP_USD:
        parser.error(f"--max-cost-usd must be in (0, {LIVE_COST_CAP_USD:g}]")
    if not os.environ.get("GEMINI_API_KEY"):
        parser.error("--eval-mode live requires GEMINI_API_KEY in the environment")
    os.environ.update(
        {
            "NOVA_EVAL_MODE": "live",
            "NOVA_EVAL_USAGE_PURPOSE": args.usage_purpose,
            "NOVA_EVAL_TEST_RUN_ID": args.test_run_id,
            "NOVA_EVAL_MAX_COST_USD": str(args.max_cost_usd),
            "NOVA_EVAL_RESERVATION_APPROVED": "true",
        }
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--phase", default="baseline", help="label for the report title")
    parser.add_argument("--out", type=Path, default=None, help="write here instead of stdout")
    parser.add_argument(
        "--eval-mode",
        choices=["replay", "live"],
        default="replay",
        help="replay (default, offline, CI-safe) | live (real Gemini on v1_copilot turns)",
    )
    parser.add_argument("--usage-purpose", choices=["live_eval", "provider_smoke"], default=None)
    parser.add_argument("--test-run-id", default=None)
    parser.add_argument("--max-cost-usd", type=float, default=None)
    parser.add_argument("--approve-reservation", action="store_true")
    args = parser.parse_args(argv)
    # The copilot path imports `app.config`, which wants these set (tests/conftest.py does the
    # same). Placeholders only: nothing here connects to a database or bucket.
    os.environ.setdefault("STORAGE_BUCKET", "nova-test")
    os.environ.setdefault("STORAGE_PROVIDER", "gcs")
    os.environ.setdefault("DATABASE_URL", "postgresql://localhost:5432/nova_test")
    os.environ.setdefault("REDIS_URL", "redis://localhost:6379")
    os.environ.setdefault("OPENAI_API_KEY", "sk-test")
    if args.eval_mode == "live":
        _require_live_guards(args, parser)
    text = render_report(args.phase, args.eval_mode)
    if args.out is None:
        print(text)
    else:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
