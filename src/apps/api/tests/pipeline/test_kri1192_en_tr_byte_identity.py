"""KRI-1192 F15: English and Turkish captions come out byte-identical.

The ten new caption languages change the caption face, the ASS base direction, the
sentence/clause marks, the phone cue budget, the Smart Caption measure, the Skia
shaping switch and the phone karaoke recipe. None of that may move a single byte for
English or Turkish.

`collect_outputs()` runs the REAL caption functions over the 24 English and Turkish
FLEURS sentences of the KRI-1192 fixture (whisper.cpp text, word times spread evenly
over each whisper segment) and returns one canonical string per output: cue lists
(cloud, phone budget, re-split, word-by-word), the ASS file of every caption style
(narrated, Talk-to-camera sentence + word pop, editor highlight/word, Smart Captions,
a per-cue font override, a creator font that lacks Turkish letters, the legacy
karaoke/plain `generate_ass`), the guided-story caption projection, the Smart Caption
measure, the phone caption recipe (sentence + karaoke) and the Skia shaping switch.

`en_tr_golden_hashes.json` holds the sha256 of every output as produced by main
before the change (fa1a64f5b, generated by running this module's `collect_outputs()`
against an export of that commit). Outputs that go through Skia text measurement are
platform-sensitive (CoreText metrics on macOS, FreeType on Linux), so they are
compared only on the platform the golden was generated on.

Regenerate (ONLY from a pre-change export, never from the changed code):
    PYTHONPATH=<export>/src/apps/api python tests/pipeline/test_kri1192_en_tr_byte_identity.py
"""

from __future__ import annotations

import hashlib
import json
import os
import sys
import tempfile
from pathlib import Path

FIXTURE_DIR = Path(__file__).resolve().parents[1] / "fixtures" / "kri1192_caption_languages"
GOLDEN = FIXTURE_DIR / "en_tr_golden_hashes.json"
LANGUAGES = ("en", "tr")


def _clips(language: str) -> list[dict]:
    data = json.loads((FIXTURE_DIR / "fleurs_whisper_turbo.json").read_text(encoding="utf-8"))
    return [clip for clip in data["clips"] if clip["language"] == language]


def _words(clip: dict, offset_s: float) -> list:
    from app.pipeline.transcribe import Word

    words = []
    for segment in clip["whisper_segments"]:
        tokens = str(segment["text"]).split()
        if not tokens:
            continue
        step = (float(segment["end_s"]) - float(segment["start_s"])) / len(tokens)
        for index, token in enumerate(tokens):
            start = offset_s + float(segment["start_s"]) + index * step
            words.append(
                Word(
                    text=token,
                    start_s=round(start, 3),
                    end_s=round(start + step * 0.9, 3),
                    confidence=0.95,
                )
            )
    return words


def _canon(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, default=str)


def _ass(write) -> str:  # noqa: ANN001 - a callable taking the output path
    with tempfile.TemporaryDirectory(prefix="kri1192_bytes_") as tmp:
        path = os.path.join(tmp, "captions.ass")
        write(path)
        return Path(path).read_text(encoding="utf-8")


def _layers(layers: list) -> str:
    return _canon([layer.model_dump(mode="json") for layer in layers])


SMART_POLICY = {
    "font_family": "TikTok Sans",
    "font_size_px": 78,
    "y_frac": 0.8,
    "width_frac": 0.84,
    "max_lines": 2,
    "color": "#FFFFFF",
    "stroke_color": "#000000",
    "stroke_width": 6,
}


def collect_outputs() -> dict[str, tuple[str, bool]]:
    """``{name: (canonical output, platform_sensitive)}`` for English and Turkish."""
    from app.pipeline import text_overlay_skia as tos
    from app.pipeline.canvas import PORTRAIT
    from app.pipeline.captions import (
        PHONE_CUE_BUDGET,
        build_plain_cues,
        build_word_cues,
        generate_ass,
        generate_ass_from_cues,
        generate_word_pop_ass,
        resplit_cues_into_sentences,
    )
    from app.pipeline.guided_caption_presentation import project_guided_caption_overlays
    from app.pipeline.narrated_assembler import resolve_caption_font
    from app.pipeline.phone_captions import compile_caption_layers
    from app.pipeline.portable_text_layout import compile_text_overlay
    from app.pipeline.render_geometry import measure_caption
    from app.pipeline.transcribe import Transcript

    out: dict[str, tuple[str, bool]] = {}
    for language in LANGUAGES:
        timeline = []
        offset = 0.0
        for clip in _clips(language):
            words = _words(clip, 0.0)
            key = f"{language}/{clip['fleurs_id']}"
            out[f"{key}/plain_cues"] = (_canon(build_plain_cues(words)), False)
            out[f"{key}/phone_cues"] = (
                _canon(build_plain_cues(words, attach_words=True, budget=PHONE_CUE_BUDGET)),
                False,
            )
            out[f"{key}/resplit_cues"] = (
                _canon(resplit_cues_into_sentences(build_plain_cues(words, attach_words=True))),
                False,
            )
            out[f"{key}/word_cues"] = (_canon(build_word_cues(words)), False)
            timeline.extend(_words(clip, offset))
            offset += float(clip["duration_s"]) + 0.5

        plain = build_plain_cues(timeline)
        cues = resplit_cues_into_sentences(build_plain_cues(timeline, attach_words=True))
        word_cues = build_word_cues(timeline)
        font = resolve_caption_font(None)
        assert font == "TikTok Sans"
        out[f"{language}/ass/narrated_plain"] = (
            _ass(lambda p: generate_ass_from_cues(plain, p, font_name=font, style="plain")),
            False,
        )
        out[f"{language}/ass/narrated_word"] = (
            _ass(lambda p: generate_ass_from_cues(word_cues, p, font_name=font, style="word")),
            False,
        )
        out[f"{language}/ass/subtitled_sentence"] = (
            _ass(
                lambda p: generate_ass_from_cues(
                    cues, p, font_name=font, style="plain", margin_v=384, pop_in=True
                )
            ),
            False,
        )
        out[f"{language}/ass/subtitled_word_pop"] = (
            _ass(lambda p: generate_word_pop_ass(cues, p, font_name=font, margin_v=384)),
            False,
        )
        out[f"{language}/ass/editor_highlight"] = (
            _ass(
                lambda p: generate_ass_from_cues(
                    cues,
                    p,
                    font_name="Montserrat",
                    style="plain",
                    margin_v=384,
                    pop_in=True,
                    appearance={
                        "highlight_spoken_word": True,
                        "highlight_color": "#C5F82A",
                        "display_style": "sentence",
                    },
                )
            ),
            False,
        )
        out[f"{language}/ass/editor_word"] = (
            _ass(
                lambda p: generate_ass_from_cues(
                    cues,
                    p,
                    font_name=font,
                    style="plain",
                    margin_v=384,
                    appearance={"highlight_spoken_word": True, "display_style": "word"},
                )
            ),
            False,
        )
        # A creator caption font that lacks Turkish letters (Big Curls: ç ğ ı ö ş ü)
        # keeps libass's own per-letter fallback: Latin text is never re-faced.
        out[f"{language}/ass/creator_font_big_curls"] = (
            _ass(
                lambda p: generate_ass_from_cues(
                    cues,
                    p,
                    font_name=resolve_caption_font("Big Curls"),
                    style="plain",
                    margin_v=384,
                    pop_in=True,
                )
            ),
            False,
        )
        overridden = [
            {**cue, "font_family": "Satisfy", "size_px": 90} if index % 3 == 0 else cue
            for index, cue in enumerate(cues)
        ]
        out[f"{language}/ass/per_cue_override"] = (
            _ass(lambda p: generate_word_pop_ass(overridden, p, font_name=font, margin_v=384)),
            False,
        )
        out[f"{language}/ass/smart"] = (
            _ass(
                lambda p: generate_ass_from_cues(
                    overridden,
                    p,
                    font_name=font,
                    style="plain",
                    margin_v=384,
                    pop_in=True,
                    smart_policy=SMART_POLICY,
                )
            ),
            True,
        )
        transcript = Transcript(words=timeline, language=language)
        out[f"{language}/ass/legacy_karaoke"] = (
            _ass(lambda p: generate_ass(transcript, 0.0, offset, p)),
            False,
        )
        out[f"{language}/ass/legacy_plain"] = (
            _ass(lambda p: generate_ass(transcript, 0.0, offset, p, style="plain", font_name=font)),
            False,
        )

        rows = [
            {
                "role": "generative_narration_caption",
                "element_id": f"c{index:03d}",
                "text": word["text"],
                "start_s": word["start_s"],
                "end_s": word["end_s"],
            }
            for index, word in enumerate(word_cues)
        ]
        for name, meta in (
            ("sentence", {"style": "sentence"}),
            ("word", {"style": "word"}),
            ("legacy", {"style": "lines"}),
            ("highlight", {"style": "sentence", "appearance": {"highlight_spoken_word": True}}),
        ):
            projected = project_guided_caption_overlays([dict(row) for row in rows], meta)
            out[f"{language}/guided/{name}"] = (_canon(projected), False)

        out[f"{language}/measure"] = (
            _canon(
                [
                    measure_caption(
                        str(cue["text"]),
                        font_family="TikTok Sans",
                        font_size_px=78,
                        width_frac=0.84,
                        y_frac=0.8,
                        max_lines=2,
                    )
                    for cue in cues
                ]
            ),
            True,
        )
        out[f"{language}/phone/sentence"] = (
            _layers(compile_caption_layers(cues, canvas_width=1080, canvas_height=1920)),
            True,
        )
        out[f"{language}/phone/word"] = (
            _layers(
                compile_caption_layers(cues, canvas_width=1080, canvas_height=1920, style="word")
            ),
            True,
        )
        statics = []
        for index, cue in enumerate(cues[:6]):
            layer, _asset = compile_text_overlay(
                {
                    "text": cue["text"],
                    "start_s": cue["start_s"],
                    "end_s": cue["end_s"],
                    "effect": "static",
                    "font_family": "TikTok Sans Bold",
                    "text_size_px": 78,
                    "position_x_frac": 0.5,
                    "position_y_frac": 0.8,
                },
                layer_id=f"static-{index}",
                canvas=PORTRAIT,
            )
            statics.append(layer.model_dump(mode="json"))
        out[f"{language}/phone/static"] = (_canon(statics), True)
        typeface = tos._resolve_typeface_for_overlay({"font_family": "TikTok Sans"}).typeface
        out[f"{language}/skia/auto_shape"] = (
            _canon([tos._auto_shape(typeface, str(cue["text"]), False) for cue in cues]),
            False,
        )
    return out


def _digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _platform() -> str:
    import platform

    return f"{sys.platform}-{platform.machine()}"


def test_english_and_turkish_caption_outputs_are_byte_identical_to_main(monkeypatch):
    # The phone recipe goldens predate the KRI-632 row budget (a cue the Kria mark forces past
    # two rows is split in time); that switch is covered in test_phone_caption_row_budget.py.
    from app.config import settings

    monkeypatch.setattr(settings, "phone_caption_row_budget_enabled", False)
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    outputs = collect_outputs()
    assert sorted(outputs) == sorted(golden["outputs"]), "output set changed"
    same_platform = golden["platform"] == _platform()
    changed = []
    for name, (text, sensitive) in sorted(outputs.items()):
        expected = golden["outputs"][name]
        assert expected["platform_sensitive"] == sensitive, name
        if sensitive and not same_platform:
            continue
        if _digest(text) != expected["sha256"]:
            changed.append(name)
    assert not changed, f"English/Turkish caption output changed: {changed}"
    if not same_platform:
        insensitive = [name for name, (_t, s) in outputs.items() if not s]
        assert len(insensitive) >= 100, "too few platform-independent outputs compared"


