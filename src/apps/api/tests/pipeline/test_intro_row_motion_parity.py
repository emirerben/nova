"""KRI-1618: the phone fixture is what the compiler makes.

`tests/fixtures/intro-row-motion-parity/{en,tr}.json` are GENERATED here from the real compile,
placement and Talking text lane (never hand-edited) and read by the KriaMediaEngine test
`IntroRowMotionRenderTests`, which draws them with the export's own text pass: each row's ink
against the cloud's, the later row on top where the script tucks onto the serif, and the late
accent drawing nothing before it enters.

Drift check: texts, fonts and times must equal a fresh build's; positions may move a pixel or two
between Skia builds, so they are compared within `_PX`. Regenerate with
`KRI1618_REGENERATE=1 pytest tests/pipeline/test_intro_row_motion_parity.py`.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

pytest.importorskip("skia")

from app.cli import verify_intro_scenes as check  # noqa: E402
from app.pipeline import intro_scene as scene_mod  # noqa: E402
from app.pipeline import overlay_verify as ov  # noqa: E402
from app.pipeline.canvas import PORTRAIT  # noqa: E402
from app.pipeline.portable_text_layout import compile_text_overlay  # noqa: E402
from app.tasks.generative_build import _text_element_burn_dicts  # noqa: E402

_DIR = Path(__file__).resolve().parents[5] / "tests" / "fixtures" / "intro-row-motion-parity"
_PX = 2.0
_PROBE_RAISE_PX = 40
_NOTE = (
    "KRI-1618: an intro title's text layers as the phone is told to draw them (the Talking text "
    "lane), with the accent row entering late and the script row tucked onto the serif row under "
    "it. probe_layers repeat them with line 2 in a second ink and raised 40 px, so the two rows' "
    "inks cross and the draw order is visible (the tuck itself crosses only a few pixels). "
    "cloud_ink_boxes are the Skia ink boxes, canvas px. Generated by "
    "src/apps/api/tests/pipeline/test_intro_row_motion_parity.py; read by "
    "IntroRowMotionRenderTests (KriaMediaEngine)."
)


def _layers(rows: list[dict]) -> tuple[list[dict], dict[str, str]]:
    variant = {
        "resolved_archetype": "subtitled",
        "text_elements": [dict(row) for row in rows],
        "duration_s": 30.0,
        "text_elements_user_edited": False,
    }
    layers, fonts = [], {}
    for index, overlay in enumerate(_text_element_burn_dicts(variant)):
        layer, font = compile_text_overlay(
            overlay, layer_id=f"text-{index}", canvas=PORTRAIT, dissolve_seed=101 + index * 37
        )
        layers.append(layer.model_dump(mode="json", exclude_none=True))
        if font is not None:
            fonts[font.id] = font.catalog_id
    return layers, fonts


def _build(language: str) -> dict:
    [(_id, _lang, title, voices, choices, _plate)] = [
        case for case in check.MOVE_CASES if case[0] == "script-tuck" and case[1] == language
    ]
    scene = check._move_scene(voices, choices)
    out = scene_mod.compile_intro_scene(
        scene, title, canvas=PORTRAIT, timeline_duration_s=30.0, language=language
    )
    assert out.rows is not None, out.reason
    rows, _receipt = check._place(out.rows, out.position)
    layers, fonts = _layers(rows)
    raised = round(rows[1]["y_frac"] - _PROBE_RAISE_PX / PORTRAIT.height, 4)
    probe, probe_fonts = _layers([rows[0], {**rows[1], "color": "#FF2020", "y_frac": raised}])
    boxes = [
        list(
            ov.text_bbox(
                ov.render_overlay_frame({**scene_mod.overlay_for_row(r), "shadow_enabled": False})
            )
        )
        for r in rows
    ]
    [accent] = [
        index
        for index, row in enumerate(rows)
        if row["source_params"]["title_look"]["style"] == "intro_accent"
    ]
    return {
        "_note": _NOTE,
        "title": title,
        "language": language,
        "accent_layer": accent,
        "accent_start_s": scene_mod.STAGGERS[scene.stagger],
        "cloud_ink_boxes": boxes,
        "fonts": {**fonts, **probe_fonts},
        "layers": layers,
        "probe_layers": probe,
    }


def _shape(fixture: dict) -> dict:
    def layer(entry: dict) -> dict:
        return {
            "id": entry["id"],
            "start": entry["start"],
            "end": entry["end"],
            "effect": entry["effect"],
            "runs": [(run["text"], run["font_asset_id"], run["fill"]) for run in entry["runs"]],
        }

    return {
        "title": fixture["title"],
        "accent": (fixture["accent_layer"], fixture["accent_start_s"]),
        "fonts": fixture["fonts"],
        "layers": [layer(entry) for entry in fixture["layers"]],
        "probe": [layer(entry) for entry in fixture["probe_layers"]],
    }


def _positions(fixture: dict) -> list[float]:
    found = [*(v for box in fixture["cloud_ink_boxes"] for v in box)]
    for entry in (*fixture["layers"], *fixture["probe_layers"]):
        found.append(entry["anchor_y"])
        found.extend(run["baseline_y"] for run in entry["runs"])
    return found


@pytest.mark.parametrize("language", ["en", "tr"])
def test_the_phone_fixture_is_what_the_compiler_makes(language):
    fresh = _build(language)
    path = _DIR / f"{language}.json"
    if os.environ.get("KRI1618_REGENERATE") == "1":
        _DIR.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(fresh, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    stored = json.loads(path.read_text(encoding="utf-8"))
    assert _shape(stored) == _shape(fresh)
    for was, now in zip(_positions(stored), _positions(fresh), strict=True):
        assert now == pytest.approx(was, abs=_PX)
