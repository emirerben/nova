"""KRI-1613: the phone fixture is what the worker compiles.

`tests/fixtures/intro-scene-sound/*.json` are GENERATED here from the real worker render (the
harness of `test_intro_scene_sound_worker.py`), never hand-edited, and read by the KriaMediaEngine
test `IntroSceneSoundExportTests`, which exports the compiled sound-effect clips through the
native exporter and finds each sound's onset in the decoded audio. Each fixture keeps the title
lines' text-layer starts separately from the clips, so the phone test judges the clips against
the entrances, not against themselves. Regenerate with
`KRI1613_REGENERATE=1 pytest tests/tasks/test_intro_scene_sound_phone_fixture.py`.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import pytest

from app.agents import _model_client
from app.services.device_render import device_status
from app.tasks import generative_build as gb
from tests.tasks.test_intro_scene_model_worker import Routing
from tests.tasks.test_intro_scene_sound_worker import _open_gates, _render
from tests.tasks.test_intro_scene_worker import EN, TR, _title_rows

_DIR = Path(__file__).resolve().parents[5] / "tests" / "fixtures" / "intro-scene-sound"
_NOTE = (
    "KRI-1613: an intro scene's sound as the phone is told to play it (the compiled `sfx` "
    "track) beside the entrances of its title lines (their text layers' starts), from the real "
    "Talking worker. Generated by "
    "src/apps/api/tests/tasks/test_intro_scene_sound_phone_fixture.py; "
    "read by IntroSceneSoundExportTests (KriaMediaEngine)."
)
CASES: dict[str, dict[str, Any]] = {
    "accent_en": {
        "title": EN,
        "language": "en",
        "answer": {"stagger": "accent_after", "sound": "accent-pop", "sound_cue": "accent"},
    },
    "each_tr": {
        "title": TR,
        "language": "tr",
        "answer": {"stagger": "accent_after", "sound": "soft-pop", "sound_cue": "each"},
    },
    "switch_off_en": {
        "title": EN,
        "language": "en",
        "answer": {"stagger": "accent_after", "sound": "accent-pop", "sound_cue": "accent"},
        "switch_off": True,
    },
}


def _fixture(monkeypatch, case: dict[str, Any]) -> dict[str, Any]:
    def install(answer: str) -> Routing:
        client = Routing(answer)
        monkeypatch.setattr(_model_client, "default_client", lambda: client)
        return client

    job = _render(monkeypatch, install, case["title"], case["language"], **case["answer"])
    _open_gates(monkeypatch)
    if case.get("switch_off"):
        monkeypatch.setattr(gb.settings, "intro_scene_sound_enabled", False)
    gb._run_generative_job(str(job.id))
    assert job.status == "awaiting_device", job.error_detail
    recipe = device_status(job, "subtitled").request.recipe
    lines = sorted(_title_rows(job), key=lambda r: int(r["source_params"]["title_look"]["line"]))
    layers = {
        "".join(run.text for run in layer.runs).replace(" ", "").casefold(): layer
        for layer in recipe.text_layers
    }
    entrances = [
        round(float(layers[row["text"].replace(" ", "").casefold()].start), 6) for row in lines
    ]
    accent = next(
        entrance
        for row, entrance in zip(lines, entrances, strict=True)
        if row["source_params"]["title_look"]["style"] == "intro_accent"
    )
    return {
        "_note": _NOTE,
        "language": case["language"],
        "cue": "none" if case.get("switch_off") else case["answer"]["sound_cue"],
        "fps": float(recipe.frame_rate),
        "entrances_s": entrances,
        "accent_entrance_s": accent,
        "sfx": [
            {
                "id": clip.id,
                "timeline_start": round(float(clip.timeline_start), 6),
                "source_duration": round(float(clip.source_duration), 6),
                "volume": float(clip.volume),
            }
            for track in recipe.tracks
            if track.id == "sfx"
            for clip in track.clips
        ],
    }


@pytest.mark.parametrize("name", sorted(CASES))
def test_the_phone_fixture_is_what_the_worker_compiles(monkeypatch, name):
    built = _fixture(monkeypatch, CASES[name])
    path = _DIR / f"{name}.json"
    if os.environ.get("KRI1613_REGENERATE"):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(built, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    assert json.loads(path.read_text(encoding="utf-8")) == built
